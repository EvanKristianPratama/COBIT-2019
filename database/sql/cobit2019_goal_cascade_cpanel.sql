-- COBIT 2019 goals cascade: BSC dimensions, Enterprise Goal -> Alignment Goal and Alignment Goal -> Governance/Management Objective mappings.
-- Reuses existing master data: mst_entergoals, mst_aligngoals, mst_entergoalsmetr, mst_aligngoalsmetr, mst_objective.
-- Level: P = primary, S = secondary. Additive and repeatable. Matches migration 2026_11_12_000003_create_cobit2019_goal_cascade_tables.

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `mst_cobit2019_goal_dimensions` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `goal_type` VARCHAR(10) NOT NULL,
    `goal_id` VARCHAR(20) NOT NULL,
    `bsc_dimension` VARCHAR(40) NOT NULL,
    `order_no` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `mst_cobit2019_goal_dimensions_goal_id_unique` (`goal_id`),
    KEY `mst_cobit2019_goal_dimensions_goal_type_index` (`goal_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `trs_cobit2019_eg_ag_maps` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `entergoals_id` VARCHAR(20) NOT NULL,
    `aligngoals_id` VARCHAR(20) NOT NULL,
    `level` CHAR(1) NOT NULL,
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `trs_c19_eg_ag_unique` (`entergoals_id`, `aligngoals_id`),
    KEY `trs_cobit2019_eg_ag_maps_aligngoals_id_index` (`aligngoals_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `trs_cobit2019_ag_objective_maps` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `aligngoals_id` VARCHAR(20) NOT NULL,
    `objective_id` VARCHAR(20) NOT NULL,
    `level` CHAR(1) NOT NULL,
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `trs_c19_ag_obj_unique` (`aligngoals_id`, `objective_id`),
    KEY `trs_cobit2019_ag_objective_maps_objective_id_index` (`objective_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


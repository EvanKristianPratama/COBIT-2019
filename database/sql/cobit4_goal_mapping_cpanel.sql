-- Criteria: P = primary, S = secondary, NULL = none.

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS=0;

CREATE TABLE IF NOT EXISTS `mst_cobit4_business_goals` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `code` SMALLINT UNSIGNED NOT NULL,
    `perspective` VARCHAR(40) NOT NULL,
    `title` VARCHAR(255) NOT NULL,
    `order_no` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `mst_cobit4_business_goals_code_unique` (`code`),
    KEY `mst_cobit4_business_goals_perspective_index` (`perspective`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `mst_cobit4_it_goals` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `code` SMALLINT UNSIGNED NOT NULL,
    `title` VARCHAR(255) NOT NULL,
    `criteria_effectiveness` CHAR(1) NULL DEFAULT NULL,
    `criteria_efficiency` CHAR(1) NULL DEFAULT NULL,
    `criteria_confidentiality` CHAR(1) NULL DEFAULT NULL,
    `criteria_integrity` CHAR(1) NULL DEFAULT NULL,
    `criteria_availability` CHAR(1) NULL DEFAULT NULL,
    `criteria_compliance` CHAR(1) NULL DEFAULT NULL,
    `criteria_reliability` CHAR(1) NULL DEFAULT NULL,
    `order_no` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `mst_cobit4_it_goals_code_unique` (`code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `trs_cobit4_business_it_goal_maps` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `business_goal_id` BIGINT UNSIGNED NOT NULL,
    `it_goal_id` BIGINT UNSIGNED NOT NULL,
    `order_no` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `trs_c4_bg_itg_unique` (`business_goal_id`, `it_goal_id`),
    KEY `trs_cobit4_business_it_goal_maps_it_goal_id_foreign` (`it_goal_id`),
    CONSTRAINT `trs_cobit4_business_it_goal_maps_business_goal_id_foreign` FOREIGN KEY (`business_goal_id`) REFERENCES `mst_cobit4_business_goals` (`id`) ON DELETE CASCADE,
    CONSTRAINT `trs_cobit4_business_it_goal_maps_it_goal_id_foreign` FOREIGN KEY (`it_goal_id`) REFERENCES `mst_cobit4_it_goals` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `trs_cobit4_it_goal_process_maps` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `it_goal_id` BIGINT UNSIGNED NOT NULL,
    `process_code` VARCHAR(20) NOT NULL,
    `order_no` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `trs_c4_itg_proc_unique` (`it_goal_id`, `process_code`),
    KEY `trs_cobit4_it_goal_process_maps_process_code_index` (`process_code`),
    CONSTRAINT `trs_cobit4_it_goal_process_maps_it_goal_id_foreign` FOREIGN KEY (`it_goal_id`) REFERENCES `mst_cobit4_it_goals` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


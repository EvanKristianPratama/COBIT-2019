    UNIQUE KEY `mst_cobit5_catalog_practices_code_unique` (`code`),
    KEY `mst_cobit5_catalog_practices_gamo_code_index` (`gamo_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


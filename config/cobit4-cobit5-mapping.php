$expandTargets = static function (string ...$codes): array {
    $expanded = [];

    foreach ($codes as $code) {
        if (preg_match('/^((?:EDM|APO|BAI|DSS|MEA)\d{2})\.(\d{2})-(\d{2})$/', $code, $match)) {
            foreach (range((int) $match[2], (int) $match[3]) as $number) {
                $expanded[] = $match[1].'.'.str_pad((string) $number, 2, '0', STR_PAD_LEFT);
            }

            continue;
        }

        $expanded[] = $code;
    }

    return array_values(array_unique($expanded));
};

$mapped = static function (string $code, string $domain, string $title, string ...$targets) use ($expandTargets): array {
    return [
        'code' => $code,
        'domain' => $domain,
        'title' => $title,
        'mapping_status' => 'mapped',
        'mapping_note' => null,
        'review_note' => null,
        'display_targets' => array_values(array_unique($targets)),
        'targets' => $expandTargets(...$targets),
    ];
};

